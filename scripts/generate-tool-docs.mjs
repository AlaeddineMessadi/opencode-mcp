#!/usr/bin/env node

// Deterministic reference generated from the exact registration catalogs.
// No network requests, model calls, or job-store writes are permitted here.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { createServer } from "../dist/app.js";
import { capabilities, capabilityFor } from "../dist/backends/capabilities.js";

const offline = new Proxy({}, {
  get: (_target, property) => property === "getBackendIdentity" ? () => ({ kind: "v1", connectionSource: "explicit", processOwnership: "external", survivesDisconnect: true })
    : () => { throw new Error(`Documentation generation attempted runtime operation: ${String(property)}`); },
});
const full = createServer(offline, offline, "full").catalog;
const essential = new Set(createServer(offline, offline, "essential").catalog.map((tool) => tool.name));
const workflows = new Set("setup ask reply run fire check conversation sessions_overview context review_changes wait provider_test status".split(" ").map((name) => `opencode_${name}`));
const groups = [
  ["Workflow Tools", (n) => workflows.has(n)],
  ["Job Tools", (n) => n.startsWith("opencode_job_")],
  ["Question Tools", (n) => n.startsWith("opencode_question_")],
  ["Session Tools", (n) => n.startsWith("opencode_session_") || n === "opencode_permission_list"],
  ["Message Tools", (n) => /^opencode_(message_|command_execute$|shell_execute$)/.test(n)],
  ["File & Search Tools", (n) => /^opencode_(file_|find_)/.test(n)],
  ["Config Tools", (n) => n.startsWith("opencode_config_")],
  ["Provider & Auth Tools", (n) => /^opencode_(provider_|auth_)/.test(n)],
  ["TUI Control Tools", (n) => n.startsWith("opencode_tui_")],
  ["Project Tools", (n) => n.startsWith("opencode_project_")],
  ["Event Tools", (n) => n.startsWith("opencode_events_")],
  ["Global Tools", (n) => n === "opencode_health"],
  ["System & Monitoring Tools", () => true],
];
const cell = (value) => String(value ?? "").replaceAll("|", "\\|").replaceAll("\n", " ").replaceAll("\r", " ");
const anchor = (value) => value.toLowerCase().replaceAll(" & ", "--").replaceAll(" ", "-");
function type(schema) {
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  if (Object.hasOwn(schema, "const")) return JSON.stringify(schema.const);
  if (schema.anyOf || schema.oneOf) return (schema.anyOf ?? schema.oneOf).map(type).join(" | ");
  if (schema.type === "array") return `array<${type(schema.items ?? {})}>`;
  if (Array.isArray(schema.type)) return schema.type.join(" | ");
  return schema.type ?? (schema.$ref ? schema.$ref : "unknown");
}
function details(schema) {
  const constraints = [
    ["minimum", "minimum"], ["maximum", "maximum"], ["minLength", "minimum length"],
    ["maxLength", "maximum length"], ["minItems", "minimum items"], ["maxItems", "maximum items"],
    ["pattern", "pattern"], ["default", "default"],
  ].filter(([key]) => Object.hasOwn(schema, key)).map(([key, label]) => `${label}: ${JSON.stringify(schema[key])}`);
  return [schema.description, ...constraints].filter(Boolean).join("; ");
}
function properties(schema, input = false) {
  const entries = Object.entries(schema.properties ?? {});
  if (!entries.length) return input ? "No input parameters.\n" : "No fixed output fields.\n";
  return [
    `| ${input ? "Parameter" : "Field"} | Type | Required | Description |`,
    "|---|---|---|---|",
    ...entries.map(([name, field]) => `| \`${name}\` | ${cell(type(field))} | ${(schema.required ?? []).includes(name) ? "yes" : "no"} | ${cell(details(field))} |`),
  ].join("\n") + "\n";
}
const sections = new Map(groups.map(([name]) => [name, []]));
const names = new Set();
for (const tool of [...full].sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0)) {
  if (names.has(tool.name)) throw new Error(`Duplicate tool: ${tool.name}`);
  names.add(tool.name);
  if (!capabilityFor(tool.name)) throw new Error(`Missing capability entry: ${tool.name}`);
  sections.get(groups.find(([, matches]) => matches(tool.name))[0]).push(tool);
}
const lines = [
  "# Tools Reference", "",
  "<!-- Generated by scripts/generate-tool-docs.mjs. Run npm run docs:generate; do not edit directly. -->", "",
  `The full profile exposes **${full.length} tools**; the essential profile exposes **${essential.size} tools**. This reference is generated from the registered input/output schemas and behavior annotations.`, "",
  "Set `OPENCODE_TOOL_PROFILE=essential` for the smaller catalog; `full` is the default. Profile availability is listed for each tool. Profiles control discovery, not OpenCode permissions.", "",
  "Tool names and schemas stay available across backends. Backend support is listed below and in the [generated compatibility inventory](compatibility.md); unavailable operations fail before mutation. Supported tools may have backend-specific option restrictions described in [migration](../MIGRATION.md).", "",
  "## Input and Output Contracts", "",
  "When present, `directory` means an absolute path on the OpenCode server. Global authentication tools omit it; local project initialization uses `path`. See [configuration](configuration.md) for scope and [examples](examples.md) for workflows.", "",
  "Results retain readable MCP `content` and provide `structuredContent`. Structured outputs include `text` and `isError`; generic JSON lives in `data`, while async tools provide identifiers and state fields. Tool errors also set the MCP result's `isError`. Inspect state rather than parsing text. An observation timeout can return a running state without an error or cancellation.", "",
  "Async states are `accepted`, `running`, `input_required`, `completed`, `failed`, `cancelled`, and `unknown`. Native MCP task execution is negotiated separately from ordinary tool calls. See [architecture](architecture.md).", "",
  "Annotations are behavior hints, not an authorization boundary. Nested structures and constraints are included in each tool's expandable JSON schema.", "",
  "## Categories", "",
  ...[...sections].filter(([, tools]) => tools.length).map(([name, tools]) => `- [${name} (${tools.length})](#${anchor(name)})`), "",
];
for (const [section, tools] of sections) {
  if (!tools.length) continue;
  lines.push(`## ${section}`, "");
  for (const tool of tools) {
    const capability = capabilityFor(tool.name);
    lines.push(`### \`${tool.name}\``, "", tool.description, "",
      `**Profiles:** ${essential.has(tool.name) ? "full, essential" : "full"}.`, "",
      `**Backends:** V1 ${capability.v1}; V2 ${capability.v2}.${capability.reason ? ` ${capability.reason}` : ""}`, "",
      `**Annotations:** ${Object.entries(tool.annotations).map(([name, value]) => `\`${name}: ${value}\``).join(", ")}.`, "",
      "#### Parameters", "", properties(tool.inputSchema, true),
      "#### Structured output", "", properties(tool.outputSchema),
      "<details>", "<summary>Complete input and output JSON schemas</summary>", "",
      "```json", JSON.stringify({ inputSchema: tool.inputSchema, outputSchema: tool.outputSchema }, null, 2), "```", "", "</details>", "");
  }
}
const output = lines.join("\n");
const toolCapabilities = capabilities.filter(item => item.kind === "tool");
const countV2 = status => toolCapabilities.filter(item => item.v2 === status).length;
const compatibility = [
  "# Backend Compatibility", "",
  "<!-- Generated by scripts/generate-tool-docs.mjs from src/backends/capabilities.ts. Do not edit directly. -->", "",
  `The catalog contains **${toolCapabilities.length} tools**. V1 supports all ${toolCapabilities.length}; V2 has **${countV2("supported")} supported tools**, **${countV2("unsupported")} planned V1-only exceptions**, and **${countV2("blocked")} operation blocked by an upstream contract limitation**.`, "",
  "The full and essential profiles keep their existing names and schemas. An unavailable V2 call returns a structured `UNSUPPORTED_CAPABILITY` error before mutation; it never falls back to a V1 route. Resource and prompt inventories are included below.", "",
  "## Meaning of support", "",
  "- **supported:** an adapter mapping exists. Individual options may still require explicit preflight rejection; see [migration](../MIGRATION.md). This status does not claim that every option or live execution has been verified.",
  "- **unsupported:** an intentional V1-only exception for this milestone.",
  "- **blocked:** a required operation could not preserve the public behavior with the pinned upstream contract. It remains an outstanding compatibility limitation.", "",
  "The integration targets are OpenCode V1 `opencode-ai@1.18.31` and OpenCode V2 `@opencode/cli@2.0.6`, with `@opencode/client@2.0.6` pinned. Version recognition and fixture coverage are separate from [live verification evidence](releasing.md). Doctor reports the target version without claiming that a live integration check has passed.", "",
  "V2 whole-message reverts remain staged and reversible. Because upstream 2.0.6 automatically commits staged reverts when prompting or compacting, the bridge rejects those operations until the revert is cleared with `opencode_session_unrevert` or explicitly committed outside the bridge.", "",
  "## Required upstream follow-up", "",
  ...toolCapabilities.filter(item => item.v2 === "blocked").map(item => `- **\`${item.name}\`**: ${item.reason} No detached command or guessed completion result is substituted.`), "",
];
for (const [kind, title] of [["tool", "Tools"], ["resource", "Static resources"], ["template", "Resource templates"], ["prompt", "Prompts"]]) {
  const entries = capabilities.filter(item => item.kind === kind).sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0);
  compatibility.push(`## ${title} (${entries.length})`, "", "| Name | V1 | V2 | Notes |", "|---|---|---|---|",
    ...entries.map(item => `| \`${item.name}\` | ${item.v1} | ${item.v2} | ${cell(item.reason ?? "")} |`), "");
}
for (const [file, contents] of [["tools.md", output], ["compatibility.md", compatibility.join("\n")]]) {
  const destination = fileURLToPath(new URL(`../docs/${file}`, import.meta.url));
  if (process.argv.includes("--check")) {
    const current = await readFile(destination, "utf8").catch(() => "");
    // Git may check out Markdown with CRLF on Windows; compare logical lines.
    if (current.replaceAll("\r\n", "\n") !== contents) {
      console.error(`Generated docs/${file} is stale. Run npm run docs:generate and commit generated documentation.`);
      process.exitCode = 1;
    }
  } else {
    await writeFile(destination, contents);
    console.log(`Generated docs/${file}`);
  }
}
